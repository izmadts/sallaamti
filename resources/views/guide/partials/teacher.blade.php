<h3>Your Role</h3>
<p>Teachers run one or more Quran Live Class Groups — a group is a set of admitted students at the same level, assigned to you by an admin after your account is vetted and approved. Everything you need lives under <strong>My Groups</strong>.</p>

<h3>Daily Class Link</h3>
<p>Each day, open your group and post today's class link (Zoom/Google Meet/whatever you use) — this is what parents see under their child's "My Quran Class" the moment you post it. Only vetted teachers (approved by an admin) can access this at all.</p>

<h3>Assessments & Progress Reports</h3>
<p>Record a short assessment after a class session, and file a monthly progress report per student — parents see these under their own "My Progress" page, so keep them specific and honest; they're a big part of how a family judges the class.</p>

<h3>Messaging Parents</h3>
<p>Reply directly to a parent's message from a student's detail page — this is the same conversation thread they see when they message you from their side. Every reply notifies the parent.</p>

<h3>Your Students</h3>
<p>The <strong>Students</strong> page lists everyone across all your groups, with a detail page per student showing their admission info, message history, and every assessment/progress report you've filed.</p>

<h3>Your Schedule</h3>
<p>The <strong>Schedule</strong> page shows every group you teach across the week at a glance, so you can plan around them.</p>

