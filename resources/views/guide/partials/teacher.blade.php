<h3>آپ کا کردار</h3>
<p>اساتذہ ایک یا زیادہ قرآن لائیو کلاس گروپس چلاتے ہیں — ایک گروپ ایک ہی درجے پر داخل شدہ طلبہ کا مجموعہ ہوتا ہے، جو آپ کے اکاؤنٹ کی جانچ اور منظوری کے بعد ایڈمن آپ کو تفویض کرتا ہے۔ آپ کو درکار ہر چیز <strong>میرے گروپس</strong> کے تحت موجود ہے۔</p>

<h3>روزانہ کلاس لنک</h3>
<p>ہر روز، اپنا گروپ کھولیں اور آج کا کلاس لنک (زوم/گوگل میٹ/جو بھی استعمال کرتے ہیں) پوسٹ کریں — جیسے ہی آپ پوسٹ کریں، والدین اسے اپنے بچے کی "میری قرآن کلاس" کے تحت دیکھ لیتے ہیں۔ صرف جانچے گئے اساتذہ (ایڈمن سے منظور شدہ) ہی اس تک رسائی رکھتے ہیں۔</p>

<h3>جائزے اور پیش رفت رپورٹس</h3>
<p>کلاس سیشن کے بعد ایک مختصر جائزہ درج کریں، اور ہر طالب علم کے لیے ماہانہ پیش رفت رپورٹ جمع کروائیں — والدین انہیں اپنے "میری پیش رفت" صفحے کے تحت دیکھتے ہیں، اس لیے انہیں مخصوص اور دیانتدارانہ رکھیں؛ یہ اس بات میں بڑا کردار ادا کرتی ہیں کہ کوئی خاندان کلاس کو کیسے جانچتا ہے۔</p>

<h3>والدین کو پیغام رسانی</h3>
<p>طالب علم کے تفصیلی صفحے سے براہ راست والدین کے پیغام کا جواب دیں — یہ وہی گفتگو کا سلسلہ ہے جو وہ اپنی طرف سے آپ کو پیغام بھیجتے وقت دیکھتے ہیں۔ ہر جواب پر والدین کو اطلاع دی جاتی ہے۔</p>

<h3>آپ کے طلبہ</h3>
<p><strong>طلبہ</strong> کا صفحہ آپ کے تمام گروپس کے طلبہ کی فہرست دکھاتا ہے، ہر طالب علم کے لیے ایک تفصیلی صفحہ جس میں ان کی داخلہ معلومات، پیغامات کی تاریخ، اور آپ کے جمع کردہ ہر جائزہ/پیش رفت رپورٹ شامل ہے۔</p>

<h3>آپ کا شیڈول</h3>
<p><strong>شیڈول</strong> کا صفحہ ہفتے بھر میں آپ کے پڑھائے جانے والے تمام گروپس کو ایک نظر میں دکھاتا ہے، تاکہ آپ ان کے مطابق منصوبہ بندی کر سکیں۔</p>

