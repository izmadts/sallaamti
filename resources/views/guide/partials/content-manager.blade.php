<h3>آپ کا کردار</h3>
<p>مواد مینیجرز (منیجر/بلاگر کردار، یا ایڈمن) بلاگ پوسٹس لکھتے اور شائع کرتے ہیں — طویل مضامین جو مختصر، کمیونٹی کی جانب سے جمع کرائی گئی کمیونٹی پوسٹس سے مختلف ہیں۔</p>

<h3>پوسٹ لکھنا</h3>
<p><strong>ایڈمن → بلاگ پوسٹس</strong> کے تحت، ایڈیٹر ایک مکمل رچ ٹیکسٹ ایڈیٹر ہے (ورڈ/گوگل ڈاکس سے براہ راست پیسٹ کریں، عنوانات، لنکس، تصاویر فارمیٹ کریں) — محفوظ کرنے پر ہر چیز خودکار طور پر صاف کر دی جاتی ہے، تاکہ پیسٹ شدہ HTML کوئی غیر محفوظ چیز جیسے اسکرپٹس متعارف نہ کروا سکے۔</p>
<ul>
    <li>نئی پوسٹس <strong>ڈرافٹ</strong> کے طور پر شروع ہوتی ہیں — جب تک آپ شائع نہ کریں، صرف آپ (اور ایڈمنز/منیجرز) ہی انہیں دیکھ سکتے ہیں۔</li>
    <li>اگر آپ خاص طور پر بلاگر کردار رکھتے ہیں (ایڈمن/منیجر نہیں)، تو آپ صرف اپنی پوسٹس دیکھ اور ترمیم کر سکتے ہیں، دوسروں کی نہیں۔</li>
    <li>کور تصاویر اختیاری مگر تجویز کردہ ہیں — یہ بلاگ انڈیکس اور سوشل شیئر لنک پیش نظاروں میں دکھائی جاتی ہیں۔</li>
    <li>ہر پوسٹ کو اس کے عنوان سے ایک منفرد، SEO دوست ویب پتہ خودکار طور پر مل جاتا ہے۔</li>
</ul>

<h3>شائع کرنا</h3>
<p>جب آپ ڈرافٹ سے مطمئن ہوں، <strong>شائع کریں</strong> استعمال کریں — یہ فوراً اپنے مستقل پتے پر لائیو ہو جاتی ہے اور سرچ انجنز کے تلاش کرنے کے لیے سائٹ میپ میں شامل ہو جاتی ہے۔ <strong>غیر شائع کریں</strong> اسے کسی بھی وقت واپس ڈرافٹ میں لے جاتا ہے بغیر حذف کیے یا آپ کا مواد کھوئے۔</p>

