<h3>Your Role</h3>
<p>Content Managers (Manager/Blogger roles, or Admin) write and publish Blog Posts — long-form articles distinct from the shorter, community-submitted Community Posts.</p>

<h3>Writing a Post</h3>
<p>Under <strong>Admin → Blog Posts</strong>, the editor is a full rich-text editor (paste directly from Word/Google Docs, format headings, links, images) — everything is automatically sanitized on save, so pasted HTML can't introduce anything unsafe like scripts.</p>
<ul>
    <li>New posts start as <strong>Draft</strong> — only you (and Admins/Managers) can see them until you publish.</li>
    <li>If you hold the Blogger role specifically (not Admin/Manager), you can only see and edit your own posts, not everyone else's.</li>
    <li>Cover images are optional but recommended — they show on the blog index and in social-share link previews.</li>
    <li>Each post automatically gets a unique, SEO-friendly web address from its title.</li>
</ul>

<h3>Publishing</h3>
<p>Once you're happy with a draft, use <strong>Publish</strong> — it goes live immediately at its permanent address and is added to the sitemap so search engines can find it. <strong>Unpublish</strong> pulls it back to Draft anytime without deleting it or losing your content.</p>

