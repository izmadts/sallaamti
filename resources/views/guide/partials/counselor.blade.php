<h3>Your Role</h3>
<p>Counselors provide family counseling sessions to members. Your public bio (set under Profile) is what members see when choosing who to book with — keep it warm and clear about what you can help with.</p>

<h3>Availability</h3>
<p>Under <strong>My Availability</strong>, add the time slots you're open for bookings — members can only book a session during a slot you've actually opened. Remove a slot anytime; it just stops new bookings, it doesn't cancel anything already booked in it.</p>

<h3>Handling Bookings</h3>
<p>New requests appear under <strong>My Bookings</strong> as "Requested." From there you can:</p>
<ul>
    <li><strong>Confirm</strong> — locks in the session and notifies the member.</li>
    <li><strong>Reply</strong> — message the member before the session if you need more context, through a private thread attached to their booking.</li>
    <li><strong>Complete</strong> — mark a finished session, with optional private notes for your own records.</li>
    <li><strong>Cancel</strong> — with a reason the member sees.</li>
    <li><strong>Mark No-Show</strong> — for a session the member didn't attend.</li>
</ul>
<p>Every status change (confirmed, replied to, completed, cancelled) notifies the member automatically — you don't need to message them separately just to tell them something changed.</p>

