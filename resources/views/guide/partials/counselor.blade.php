<h3>آپ کا کردار</h3>
<p>کاؤنسلرز ممبران کو فیملی کاؤنسلنگ سیشنز فراہم کرتے ہیں۔ آپ کا عوامی تعارف (پروفائل کے تحت سیٹ کیا گیا) وہی ہے جو ممبران بکنگ کے لیے کاؤنسلر منتخب کرتے وقت دیکھتے ہیں — اسے گرمجوشی سے بھرا اور واضح رکھیں کہ آپ کس چیز میں مدد کر سکتے ہیں۔</p>

<h3>دستیابی</h3>
<p><strong>میری دستیابی</strong> کے تحت، وہ اوقات شامل کریں جن میں آپ بکنگ کے لیے دستیاب ہیں — ممبران صرف اسی وقت میں بکنگ کر سکتے ہیں جو آپ نے کھولا ہو۔ کسی بھی وقت کوئی وقت ہٹا دیں؛ اس سے صرف نئی بکنگز رکنے میں مدد ملتی ہے، پہلے سے بک شدہ کچھ منسوخ نہیں ہوتا۔</p>

<h3>بکنگز کا انتظام</h3>
<p>نئی درخواستیں <strong>میری بکنگز</strong> کے تحت "درخواست شدہ" کے طور پر نظر آتی ہیں۔ وہاں سے آپ:</p>
<ul>
    <li><strong>تصدیق کریں</strong> — سیشن کو حتمی کرتا ہے اور ممبر کو مطلع کرتا ہے۔</li>
    <li><strong>جواب دیں</strong> — اگر مزید تفصیل درکار ہو تو سیشن سے پہلے، بکنگ سے منسلک نجی سلسلے کے ذریعے ممبر کو پیغام بھیجیں۔</li>
    <li><strong>مکمل کریں</strong> — ایک ختم شدہ سیشن نشان زد کریں، اپنے ریکارڈ کے لیے اختیاری نجی نوٹس کے ساتھ۔</li>
    <li><strong>منسوخ کریں</strong> — ایک وجہ کے ساتھ جو ممبر کو نظر آتی ہے۔</li>
    <li><strong>عدم حاضری نشان زد کریں</strong> — اس سیشن کے لیے جس میں ممبر شریک نہیں ہوا۔</li>
</ul>
<p>ہر حیثیت کی تبدیلی (تصدیق شدہ، جواب دیا گیا، مکمل، منسوخ) خودکار طور پر ممبر کو مطلع کرتی ہے — آپ کو صرف کچھ بدلنے کی اطلاع دینے کے لیے الگ سے پیغام بھیجنے کی ضرورت نہیں۔</p>

